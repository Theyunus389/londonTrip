const normalise = (name: string) =>
  name
    .toLowerCase()
    .replace(/[’]/g, "'")
    .replace(/[^a-z0-9]/g, "");
export function knownPhoto(name: string) {
  return photos.find((p) =>
    p.names.some((n) => normalise(n) === normalise(name)),
  );
}
